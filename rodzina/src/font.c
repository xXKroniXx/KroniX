#define NGLYPH ((int)(sizeof(SRC) / sizeof(SRC[0])))
static Glyph G[NGLYPH];
static Glyph *asciiMap[128];

void font_init(void) {
  for (int i = 0; i < NGLYPH; i++) {
    Glyph *g = &G[i];
    memset(g, 0, sizeof(*g));
    g->cp = SRC[i].cp;
    const char *p = SRC[i].g;
    int row = 0, col = 0, w = 0;
    for (; *p && row < 11; p++) {
      if (*p == '|') { row++; col = 0; continue; }
      if (*p == '#') g->rows[row] |= (unsigned short)(1 << col);
      col++;
      if (col > w) w = col;
    }
    g->w = w ? w : 3;
    if (g->cp < 128) asciiMap[g->cp] = g;
  }
}

static const Glyph *glyph(int cp) {
  if (cp < 128) return asciiMap[cp] ? asciiMap[cp] : asciiMap['?'];
  for (int i = 0; i < NGLYPH; i++) if (G[i].cp == cp) return &G[i];
  return asciiMap['?'];
}

int utf8_next(const char **pp) {
  const unsigned char *p = (const unsigned char *)*pp;
  int c = *p;
  if (!c) return 0;
  if (c < 0x80) { *pp += 1; return c; }
  if ((c & 0xE0) == 0xC0 && p[1]) { *pp += 2; return ((c & 0x1F) << 6) | (p[1] & 0x3F); }
  if ((c & 0xF0) == 0xE0 && p[1] && p[2]) { *pp += 3; return ((c & 0x0F) << 12) | ((p[1] & 0x3F) << 6) | (p[2] & 0x3F); }
  *pp += 1;
  return '?';
}

/* Kod koloru "{x}" — zwraca 1 i przesuwa wskaźnik, jeśli tu jest. */
static int color_code(const char **pp, u32 *col, u32 def) {
  const char *p = *pp;
  if (p[0] == '{' && p[1] && p[2] == '}') {
    if (col) *col = p[1] == '-' ? def : pal(p[1]);
    *pp += 3;
    return 1;
  }
  return 0;
}

static void draw_glyph(const Glyph *g, int x, int y, u32 col, int scale) {
  for (int r = 0; r < 11; r++) {
    unsigned short bits = g->rows[r];
    if (!bits) continue;
    for (int c = 0; c < g->w; c++)
      if (bits & (1 << c)) {
        if (scale == 1) gfx_pset(x + c, y + r, col);
        else gfx_rect(x + c * scale, y + r * scale, scale, scale, col);
      }
  }
}

static int draw_impl(int x, int y, const char *s, u32 col, int scale, int maxChars, int shadow) {
  int cx = x, maxw = 0, count = 0;
  u32 def = col, cur = col;
  const char *p = s;
  while (*p) {
    if (color_code(&p, &cur, def)) continue;
    int cp = utf8_next(&p);
    if (cp == '\n') { cx = x; y += LINE_H * scale; continue; }
    if (maxChars >= 0 && count >= maxChars) break;
    const Glyph *g = glyph(cp);
    if (shadow) draw_glyph(g, cx + 1, y + 1, pal('i'), scale);
    draw_glyph(g, cx, y, cur, scale);
    cx += (g->w + 1) * scale;
    if (cx - x > maxw) maxw = cx - x;
    count++;
  }
  return maxw;
}

int text_draw(int x, int y, const char *s, u32 col) { return draw_impl(x, y, s, col, 1, -1, 0); }
int text_draw_sh(int x, int y, const char *s, u32 col) { return draw_impl(x, y, s, col, 1, -1, 1); }
int text_draw_big(int x, int y, const char *s, u32 col, int scale) { return draw_impl(x, y, s, col, scale, -1, 1); }
int text_draw_n(int x, int y, const char *s, u32 col, int n) { return draw_impl(x, y, s, col, 1, n, 1); }

int text_width(const char *s) {
  int w = 0, maxw = 0;
  const char *p = s;
  while (*p) {
    if (color_code(&p, NULL, 0)) continue;
    int cp = utf8_next(&p);
    if (cp == '\n') { w = 0; continue; }
    w += glyph(cp)->w + 1;
    if (w > maxw) maxw = w;
  }
  return maxw > 0 ? maxw - 1 : 0;
}

/* Zawija tekst po słowach do szerokości maxw; zachowuje aktywny kolor między liniami. */
int text_wrap(const char *s, int maxw, char out[][160], int maxlines) {
  int n = 0;
  char line[160] = "";
  char active[4] = "";
  const char *p = s;
  while (*p && n < maxlines) {
    if (*p == '\n') {
      snprintf(out[n++], 160, "%s", line);
      snprintf(line, sizeof line, "%s", active);
      p++;
      continue;
    }
    if (*p == ' ') { p++; if (line[0] && strcmp(line, active) != 0) strncat(line, " ", sizeof line - strlen(line) - 1); continue; }
    const char *start = p;
    while (*p && *p != ' ' && *p != '\n') p++;
    char word[160];
    int wl = (int)(p - start);
    if (wl > 150) wl = 150;
    memcpy(word, start, wl);
    word[wl] = 0;
    char trial[320];
    snprintf(trial, sizeof trial, "%s%s", line, word);
    if (text_width(trial) > maxw && line[0] && strcmp(line, active) != 0) {
      int L = (int)strlen(line);
      while (L > 0 && line[L - 1] == ' ') line[--L] = 0;
      snprintf(out[n++], 160, "%s", line);
      if (n >= maxlines) break;
      snprintf(line, sizeof line, "%s%s", active, word);
    } else {
      snprintf(line, sizeof line, "%s", trial);
    }
    /* śledź ostatni kod koloru w słowie */
    for (const char *q = word; *q; q++)
      if (q[0] == '{' && q[1] && q[2] == '}') {
        if (q[1] == '-') active[0] = 0;
        else { active[0] = '{'; active[1] = q[1]; active[2] = '}'; active[3] = 0; }
      }
  }
  if (line[0] && strcmp(line, active) != 0 && n < maxlines) snprintf(out[n++], 160, "%s", line);
  return n;
}
